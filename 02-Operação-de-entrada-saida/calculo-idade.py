"""
Faça um programa que peça o ano de nascimento de uma pessoa
e calcule a sua idade atual.
Depois, mostre o ano de nascimento e a idade no terminal.
"""


# Entrada de dados 
idade_atual = int (input ("digite o ano atual: "))
ano_nacsimento = int (input ("digite o ano de nascimento: "))





# processamento computacional
ano_que_nasceu = ano_nacsimento
sua_idade = idade_atual - ano_nacsimento





# Saida de infomações
print (F"Sua idade : {sua_idade}")
print (F"Ano de nascimento : {ano_que_nasceu}")

